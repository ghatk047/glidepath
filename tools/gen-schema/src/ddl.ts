import type { Model, ModelTable } from './model';

/**
 * Indexes of docs/architecture/04_data_and_api.md section 1 ("Indexes that
 * matter"). variable_value and scenario_value are covered by their primary
 * keys (tenant_id leads and the pk is exactly the listed unique key), see
 * `renderTable`; the rest are emitted here.
 */
export interface IndexSpec {
  name: string;
  table: string;
  columns: string[];
  unique: boolean;
}

export const INDEXES: IndexSpec[] = [
  { name: 'change_tenant_id_changeset_id_idx', table: 'change', columns: ['tenant_id', 'changeset_id'], unique: false },
  {
    name: 'calc_run_tenant_id_scenario_id_input_hash_key',
    table: 'calc_run',
    columns: ['tenant_id', 'scenario_id', 'input_hash'],
    unique: true,
  },
  { name: 'solver_run_tenant_id_status_idx', table: 'solver_run', columns: ['tenant_id', 'status'], unique: false },
];

/** Unique keys required by 04 section 1 that must exist as a pk or unique index. */
export const REQUIRED_UNIQUE_KEYS: { table: string; columns: string[] }[] = [
  { table: 'variable_value', columns: ['tenant_id', 'var_key', 'member_key'] },
  { table: 'scenario_value', columns: ['tenant_id', 'scenario_id', 'var_key', 'member_key'] },
];

/** Postgres reserved words that appear (or could appear) as column names. */
const RESERVED = new Set([
  'all', 'analyse', 'analyze', 'and', 'any', 'array', 'as', 'asc', 'asymmetric', 'both', 'case', 'cast', 'check',
  'collate', 'column', 'constraint', 'create', 'current_catalog', 'current_date', 'current_role', 'current_time',
  'current_timestamp', 'current_user', 'default', 'deferrable', 'desc', 'distinct', 'do', 'else', 'end', 'except',
  'false', 'fetch', 'for', 'foreign', 'from', 'grant', 'group', 'having', 'in', 'initially', 'intersect', 'into',
  'lateral', 'leading', 'limit', 'localtime', 'localtimestamp', 'not', 'null', 'offset', 'on', 'only', 'or', 'order',
  'placing', 'primary', 'references', 'returning', 'select', 'session_user', 'some', 'symmetric', 'table', 'then',
  'to', 'trailing', 'true', 'union', 'unique', 'user', 'using', 'variadic', 'when', 'where', 'window', 'with',
]);

export function ident(name: string): string {
  if (/^[a-z_][a-z0-9_]*$/.test(name) && !RESERVED.has(name)) return name;
  return `"${name.replace(/"/g, '""')}"`;
}

function lit(s: string): string {
  return `'${s.replace(/'/g, "''")}'`;
}

function cols(c: string[]): string {
  return c.map(ident).join(', ');
}

function checkName(n: string): string {
  if (n.length > 63) throw new Error(`identifier "${n}" exceeds 63 characters`);
  return n;
}

function renderTable(t: ModelTable): string {
  const lines: string[] = [];
  for (const c of t.columns) {
    let l = `  ${ident(c.name)} ${c.sqlType}`;
    if (c.notNull && c.sqlType !== 'bigserial') l += ' NOT NULL';
    if (c.defaultSql) l += ` DEFAULT ${c.defaultSql}`;
    lines.push(l);
  }
  lines.push(`  CONSTRAINT ${checkName(`${t.name}_pkey`)} PRIMARY KEY (${cols(t.primaryKey)})`);
  for (const u of t.uniques) {
    lines.push(`  CONSTRAINT ${checkName(u.name)} UNIQUE (${cols(u.columns)})`);
  }
  for (const f of t.fks) {
    lines.push(
      `  CONSTRAINT ${checkName(f.name)} FOREIGN KEY (${cols(f.columns)}) REFERENCES ${ident(f.refTable)} (${cols(f.refColumns)})`,
    );
  }
  const notes = t.unenforcedRefs.map((r) => `-- ${t.name}.${r.column}: ${r.note}\n`).join('');
  return `${notes}CREATE TABLE ${ident(t.name)} (\n${lines.join(',\n')}\n);\n`;
}

/** Renders migration 0001: extensions, enum types, tables (dependency order), indexes, comments. */
export function renderSchemaSql(model: Model): string {
  const out: string[] = [];
  out.push(
    `-- GENERATED by tools/gen-schema from docs/spec/schema.json (spec_version ${model.specVersion}). Do not edit.\n` +
      `-- Regenerate: pnpm --filter @glidepath/gen-schema generate\n` +
      `-- Runs as a plain database owner (Neon-compatible): no superuser-only statements, no role management.\n`,
  );
  if (model.extensions.length) {
    out.push(model.extensions.map((e) => `CREATE EXTENSION IF NOT EXISTS ${e};`).join('\n') + '\n');
  }
  out.push(
    model.enums
      .map((e) => `CREATE TYPE ${checkName(e.name)} AS ENUM (${e.labels.map(lit).join(', ')});`)
      .join('\n') + '\n',
  );
  for (const t of model.tables) out.push(renderTable(t));

  const idx: string[] = [];
  const tableByName = new Map(model.tables.map((t) => [t.name, t]));
  for (const i of INDEXES) {
    const t = tableByName.get(i.table);
    if (!t) throw new Error(`index ${i.name}: no table ${i.table}`);
    for (const c of i.columns) if (!t.columns.some((x) => x.name === c)) throw new Error(`index ${i.name}: no column ${i.table}.${c}`);
    idx.push(`CREATE ${i.unique ? 'UNIQUE ' : ''}INDEX ${checkName(i.name)} ON ${ident(i.table)} (${cols(i.columns)});`);
  }
  for (const r of REQUIRED_UNIQUE_KEYS) {
    const t = tableByName.get(r.table);
    const ok =
      t &&
      (JSON.stringify(t.primaryKey) === JSON.stringify(r.columns) ||
        t.uniques.some((u) => JSON.stringify(u.columns) === JSON.stringify(r.columns)));
    if (!ok) throw new Error(`${r.table}: required unique key (${r.columns.join(', ')}) is not provided by pk/unique`);
  }
  out.push(idx.join('\n') + '\n');

  const comments: string[] = [];
  for (const t of model.tables) {
    if (t.description) comments.push(`COMMENT ON TABLE ${ident(t.name)} IS ${lit(t.description)};`);
    for (const c of t.columns) {
      if (c.description) comments.push(`COMMENT ON COLUMN ${ident(t.name)}.${ident(c.name)} IS ${lit(c.description)};`);
    }
  }
  out.push(comments.join('\n') + '\n');
  return out.join('\n');
}
