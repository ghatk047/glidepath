import { resolve } from 'node:path';
import { specFixtures } from '@glidepath/api-contract/testing';
import type { DimensionDefRow, ModelDefs } from '@glidepath/data-access';
import { compileModel, findScenario, resolveInputs } from '@glidepath/engine';
import { loadModelBundleFromDir, readTenantSeed } from '@glidepath/spec/node';
import { repoRoot } from '@glidepath/testkit';
import { describe, expect, it } from 'vitest';
import { buildBundle } from './bundle';

/** `ModelDefs` as `loadModelDefs` would read them for the spec's own model version. */
async function defsOf(): Promise<{ defs: ModelDefs; spec: Awaited<ReturnType<typeof specOf>> }> {
  const spec = await specOf();
  const defs: ModelDefs = {
    modelVersion: {
      id: 'mv-1',
      semver: spec.specVersion,
      status: 'published',
      notes: '',
      created_at: '2026-11-23T00:00:00.000Z',
    },
    dimensions: spec.dimensions.map((d) => ({
      dim_key: d.id,
      scope: d.scope as DimensionDefRow['scope'],
      attributes: d.attributes,
    })),
    variables: spec.variables.map((v) => ({
      var_key: v.id,
      dims: v.dims,
      label: v.label,
      unit: v.unit,
      type: v.type,
      min: v.min,
      max: v.max,
      step: v.step,
      group: v.group ?? '',
      layer: v.layer,
      role: v.role,
      ui: v.ui,
      dist: null,
      validation: null,
      legacy: null,
    })),
    nodes: spec.nodes.map((n) => ({
      node_key: n.id,
      dims: n.dims,
      expr: n.expr ?? null,
      cases: n.cases ?? null,
      members: n.members ?? null,
      unit: n.unit,
      label: n.label,
      layer: n.layer,
      output: n.output,
      overridable: true,
    })),
    leverTemplates: [],
  };
  return { defs, spec };
}
const specOf = () => loadModelBundleFromDir(resolve(repoRoot, 'docs/spec'));

/**
 * A fraction node is a ratio: coverage of the bar may pass 100% (res.coverage 1.17, vp.coverage 1.22
 * at the presets) but never reaches 2.0, where the same share in points would read 200%.
 */
const FRACTION_CEILING = 2;

describe('bundle percent scale (WEB-10)', async () => {
  const { defs, spec } = await defsOf();
  const bundle = buildBundle(defs, spec);

  it('every corporate % variable is points and g.target_pct is fraction (set by tier 2, from the registry)', () => {
    const corporate = bundle.variables.filter(
      (v) => v.layer === 'corporate' && v.unit.startsWith('%'),
    );
    expect(corporate.length).toBe(33);
    for (const v of corporate) expect([v.id, v.percentScale]).toEqual([v.id, 'points']);
    expect(bundle.variables.find((v) => v.id === 'corp.gdp')?.percentScale).toBe('points');
    expect(bundle.variables.find((v) => v.id === 'g.target_pct')?.percentScale).toBe('fraction');
    for (const v of bundle.variables.filter((x) => !x.unit.startsWith('%'))) {
      expect(v.percentScale, v.id).toBeNull();
    }
  });

  it('the contract fixtures (generated by contract/scripts, which cannot import tier 2) carry the builder scale for every variable and node', () => {
    const scales = (b: {
      variables: { id: string; percentScale: unknown }[];
      nodes: typeof b.variables;
    }) => [...b.variables, ...b.nodes].map((d) => [d.id, d.percentScale]);
    expect(scales(specFixtures.bundle as never)).toEqual(scales(bundle));
  });

  it('node scales agree with the engine: a fraction node stays a ratio (< 2), a points node exceeds 1 at some preset', async () => {
    const seedDir = resolve(repoRoot, 'docs/spec/seed/aa');
    const seed = await readTenantSeed(seedDir);
    const model = compileModel(spec, seed.dimensionMembers);
    const maxAbs = new Map<string, number>();
    for (const preset of seed.scenarios.scenarios.map((s) => s.id)) {
      const inputs = resolveInputs(spec, seed.variableValues, findScenario(seed.scenarios, preset));
      const ev = model.evaluate(inputs.values, inputs.overrides);
      for (const cell of model.index.keys()) {
        const id = cell.split('[')[0]!;
        const node = bundle.nodes.find((n) => n.id === id);
        if (!node?.percentScale) continue;
        const v = ev.get(cell);
        if (Number.isFinite(v)) maxAbs.set(id, Math.max(maxAbs.get(id) ?? 0, Math.abs(v)));
      }
    }
    const pctNodes = bundle.nodes.filter((n) => n.percentScale !== null);
    for (const n of pctNodes) {
      const m = maxAbs.get(n.id);
      if (m === undefined) continue;
      if (n.percentScale === 'points') expect(m, `${n.id} (points)`).toBeGreaterThan(1);
      else expect(m, `${n.id} (fraction)`).toBeLessThan(FRACTION_CEILING);
    }
    expect(
      pctNodes
        .filter((n) => n.percentScale === 'points')
        .map((n) => n.id)
        .sort(),
    ).toEqual(['br.eps_pct27', 'pl.lf', 'pl.op_margin', 'pl.rate', 'val.px_vs'].sort());
  });
});
