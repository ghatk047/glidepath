"""Generate the solvers' constraint defaults from docs/spec/solvers.json (MOD-11).

Usage:
  python3 -I tier2-logic/spec/scripts/dump_solver_defaults.py <repo>          # writes src/reference/solver-defaults.ts
  python3 -I tier2-logic/spec/scripts/dump_solver_defaults.py <repo> --json   # prints the data as JSON (the check test)

`min_risk_mix.constraints["gcc_hiring (optional)"]` states its default in prose ("... (default 500 in CY27)").
The number is read from that sentence; the script fails loudly if the sentence no longer has that shape, so a
spec change can never silently change or drop the default. docs/spec stays read-only.
"""
import hashlib, json, os, re, sys

repo = os.path.abspath(sys.argv[1])
as_json = "--json" in sys.argv[2:]
SOURCES = ["docs/spec/variables.json", "docs/spec/solvers.json"]


def sha256(rel):
    with open(os.path.join(repo, rel), "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


with open(os.path.join(repo, "docs", "spec", "variables.json"), encoding="utf8") as f:
    spec_version = json.load(f)["spec_version"]
with open(os.path.join(repo, "docs", "spec", "solvers.json"), encoding="utf8") as f:
    solvers = json.load(f)


def find_mix(x):
    if isinstance(x, dict):
        if x.get("id") == "min_risk_mix" and "constraints" in x:
            return x
        x = list(x.values())
    if isinstance(x, list):
        for y in x:
            r = find_mix(y)
            if r is not None:
                return r
    return None


mix = find_mix(solvers)
if mix is None:
    sys.exit("min_risk_mix not found in solvers.json")
text = mix["constraints"].get("gcc_hiring (optional)", "")
m = re.search(r"\(default (\d+(?:\.\d+)?) in CY\d+\)", text)
if not m:
    sys.exit(f"gcc_hiring default not found in solvers.json text: {text!r}")
n = float(m.group(1))
data = {
    "specVersion": spec_version,
    "sources": {s: sha256(s) for s in SOURCES},
    "gcc_hiring": int(n) if n == int(n) else n,
}
if as_json:
    json.dump(data, sys.stdout)
    sys.stdout.write("\n")
    sys.exit(0)

src = "".join(f"    '{k}': '{v}',\n" for k, v in data["sources"].items())
body = (
    "// DO NOT EDIT. Generated by tier2-logic/spec/scripts/dump_solver_defaults.py from\n"
    "// docs/spec/solvers.json (read-only). Regenerate with\n"
    "// `python3 -I tier2-logic/spec/scripts/dump_solver_defaults.py .`; src/solver-defaults.test.ts fails on any diff.\n"
    "\n"
    "import type { SolverDefaults } from '../core/solver-defaults';\n"
    "\n"
    "/** `min_risk_mix` constraint defaults the spec states in prose (gcc_hiring: hiring capacity). */\n"
    "export const REFERENCE_SOLVER_DEFAULTS: SolverDefaults = {\n"
    f"  specVersion: '{data['specVersion']}',\n"
    f"  sources: {{\n{src}  }},\n"
    f"  gcc_hiring: {data['gcc_hiring']},\n"
    "};\n"
)
out = os.path.join(repo, "tier2-logic", "spec", "src", "reference", "solver-defaults.ts")
with open(out, "w", encoding="utf8") as f:
    f.write(body)
