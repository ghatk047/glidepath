"""Generate the reference decision bounds of the solvers from docs/spec/reference/solvers_demo.py (SOL-12).

Usage:
  python3 -I tier2-logic/spec/scripts/dump_decision_bounds.py <repo>          # writes src/reference/decision-bounds.ts
  python3 -I tier2-logic/spec/scripts/dump_decision_bounds.py <repo> --json   # prints the data as JSON (the check test)

Runs the unchanged prologue of solvers_demo.py (everything before its first solver section) and takes its
decision variables: DEC (ids, in registry order), lo, hi, step and NEG. docs/spec stays read-only; the
generated module is tier 2's copy that the production solvers load. Regenerate when docs/spec or the seed
changes: src/decision-bounds.test.ts runs this script and fails on any difference.
"""
import hashlib, json, os, sys

repo = os.path.abspath(sys.argv[1])
as_json = "--json" in sys.argv[2:]
ref = os.path.join(repo, "docs", "spec", "reference")
sys.path.insert(0, ref)
demo_path = os.path.join(ref, "solvers_demo.py")
src = open(demo_path, encoding="utf8").read()
cut = src.index("# ---------------------------------------------------------------- 1.")
try:
    import numpy  # noqa: F401  (solvers_demo.py imports it; its prologue never uses it)
except ImportError:
    # CI's unit-test job has a bare CPython: a placeholder keeps the import working. Any use of it in the
    # prologue would fail loudly (AttributeError), never silently change the bounds.
    import types
    sys.modules["numpy"] = types.ModuleType("numpy")
os.chdir(repo)
argv = sys.argv
sys.argv = [demo_path, os.path.join("docs", "spec")]
scope = {"__file__": demo_path, "__name__": "solvers_demo_prologue"}
exec(compile(src[:cut], demo_path, "exec"), scope)
sys.argv = argv


def sha256(rel):
    with open(os.path.join(repo, rel), "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


SOURCES = [
    "docs/spec/variables.json",
    "docs/spec/seed/aa/scenarios.json",
    "docs/spec/reference/solvers_demo.py",
]
with open(os.path.join(repo, "docs", "spec", "variables.json"), encoding="utf8") as f:
    spec_version = json.load(f)["spec_version"]

ids = [v["id"] for v in scope["DEC"]]
data = {
    "specVersion": spec_version,
    "seed": "aa",
    "sources": {s: sha256(s) for s in SOURCES},
    "dec": ids,
    "lo": {i: scope["lo"][i] for i in ids},
    "hi": {i: scope["hi"][i] for i in ids},
    "step": {i: scope["step"][i] for i in ids},
    "neg": sorted(scope["NEG"]),
}

if as_json:
    json.dump(data, sys.stdout)
    sys.stdout.write("\n")
    sys.exit(0)


def lit(x):
    """A TS literal: single-quoted strings, numbers as Python prints them (shortest round trip)."""
    if isinstance(x, str):
        return "'" + x.replace("\\", "\\\\").replace("'", "\\'") + "'"
    return repr(x)


def record(name, m):
    rows = "".join(f"    {lit(k)}: {lit(v)},\n" for k, v in m.items())
    return f"  {name}: {{\n{rows}  }},\n"


def array(name, xs):
    rows = "".join(f"    {lit(x)},\n" for x in xs)
    return f"  {name}: [\n{rows}  ],\n"


body = (
    "// DO NOT EDIT. Generated by tier2-logic/spec/scripts/dump_decision_bounds.py from\n"
    "// docs/spec/reference/solvers_demo.py (read-only). Regenerate with\n"
    "// `python3 -I tier2-logic/spec/scripts/dump_decision_bounds.py .`; src/decision-bounds.test.ts fails on any diff.\n"
    "\n"
    "import type { DecisionBounds } from '../core/decision-bounds';\n"
    "\n"
    "/** The reference greedy's decision variables (solvers_demo.py DEC, lo, hi, step, NEG) on the seed tenant. */\n"
    "export const REFERENCE_DECISION_BOUNDS: DecisionBounds = {\n"
    f"  specVersion: {lit(data['specVersion'])},\n"
    f"  seed: {lit(data['seed'])},\n"
    + record("sources", data["sources"])
    + array("dec", data["dec"])
    + record("lo", data["lo"])
    + record("hi", data["hi"])
    + record("step", data["step"])
    + array("neg", data["neg"])
    + "};\n"
)
out = os.path.join(repo, "tier2-logic", "spec", "src", "reference", "decision-bounds.ts")
os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, "w", encoding="utf8") as f:
    f.write(body)
